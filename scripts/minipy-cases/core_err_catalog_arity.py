import math, random, statistics
from collections import deque, Counter
def coba(f):
    try:
        print(f())
    except Exception as e:
        print(type(e).__name__ + ":", e)
coba(lambda: [1, 2].append(1, 2))
coba(lambda: [1].insert(5))

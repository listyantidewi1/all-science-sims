#!/usr/bin/env python3
"""Generate src/lib/minipy/methoddocs.js: signatures and docstrings of the methods of the builtin types (and of
Counter's Python methods), for help(str.upper), help("x".upper), help(Counter.most_common) like CPython 3.13's pydoc.

Run with python3.13:  python3 scripts/gen-minipy-methoddocs.py
Each entry 'type.name': [kind, unbound signature, bound signature, __doc__]
  kind d = method_descriptor, k = classmethod (builtin), s = staticmethod (builtin), f = Python function (Counter)
"""
import collections, inspect, json, os, pydoc, sys

assert sys.version_info[:2] == (3, 13), sys.version
TYPES = {'str': str, 'list': list, 'dict': dict, 'tuple': tuple, 'set': set, 'frozenset': frozenset, 'int': int,
         'float': float, 'deque': collections.deque}
out = {}

def sig(obj):
    """the argument spec pydoc prints after the name (its 3rd line), e.g. '(self, sub[, start[, end]], /)'"""
    decl = pydoc.render_doc(obj, renderer=pydoc.plaintext).split('\n')[2]
    name = obj.__name__
    assert decl.startswith(name), decl
    rest = decl[len(name):]
    for tail in (' unbound ', ' class method of ', ' method of '):
        if tail in rest:
            rest = rest[:rest.index(tail)]
    return rest

for tname, t in TYPES.items():
    for name, attr in vars(t).items():
        if name.startswith('_'):
            continue
        kind = None
        if type(attr).__name__ == 'method_descriptor':
            kind = 'd'
        elif type(attr).__name__ == 'classmethod_descriptor':
            kind = 'k'
        elif isinstance(attr, staticmethod):
            kind = 's'
        if kind is None:
            continue
        member = getattr(t, name)
        doc = inspect.getdoc(member) or ''
        unbound = sig(member) if kind == 'd' else None
        inst = {'str': 'x', 'list': [], 'dict': {}, 'tuple': (), 'set': set(), 'frozenset': frozenset(), 'int': 1,
                'float': 1.0, 'deque': collections.deque()}[tname]
        bound = sig(getattr(inst, name))
        out[tname + '.' + name] = [kind, unbound, bound, doc]

C = collections.Counter
for name in ['most_common', 'elements', 'total', 'subtract', 'update', 'copy']:
    f = vars(C)[name]
    out['Counter.' + name] = ['f', sig(f), sig(getattr(C(), name)), inspect.getdoc(f) or '']

js = ('// minipy — signatures and docstrings of the methods of str, list, dict, tuple, set, frozenset, int, float, deque\n'
      '// and of Counter\'s Python methods (CPython 3.13), for help(). Generated by scripts/gen-minipy-methoddocs.py;\n'
      '// do not edit. \'type.name\': [kind (d method_descriptor, k classmethod, s staticmethod, f Python function),\n'
      '// unbound signature, bound signature, __doc__]\n'
      'export const METHOD_DOCS = {\n' + ',\n'.join(json.dumps(k) + ':' + json.dumps(v, ensure_ascii=False) for k, v in out.items()) + '\n};\n')
open(os.path.join(os.path.dirname(__file__), '..', 'src', 'lib', 'minipy', 'methoddocs.js'), 'w', encoding='utf-8').write(js)
print(len(out), 'entries,', len(js), 'bytes')

#!/usr/bin/env python3
"""Generate the Unicode 15.1.0 data of minipy (what CPython 3.13 uses, independent of the JS engine's Unicode version):
  src/lib/minipy/uninames.js  the character names CPython 3.13 accepts in \\N{...} escapes
  src/lib/minipy/unidata.js   the str predicates (isalpha, isdigit, isprintable, isidentifier, ...) and case mappings

Run with python3.13 (its unicodedata is Unicode 15.1.0):  python3 scripts/gen-minipy-unicode.py NameAliases.txt
NameAliases.txt is https://www.unicode.org/Public/15.1.0/ucd/NameAliases.txt (\\N{} accepts every alias type).
Algorithmic names (CJK UNIFIED IDEOGRAPH-XXXX, HANGUL SYLLABLE ..., TANGUT IDEOGRAPH-..., ...) are computed by the
JS code from the ranges written here; all other names are stored with a word dictionary and prefix sharing.
"""
import sys, unicodedata, collections, os

assert unicodedata.unidata_version == '15.1.0', unicodedata.unidata_version
ALG = ('CJK UNIFIED IDEOGRAPH-', 'CJK COMPATIBILITY IDEOGRAPH-', 'TANGUT IDEOGRAPH-', 'KHITAN SMALL SCRIPT CHARACTER-',
       'NUSHU CHARACTER-', 'HANGUL SYLLABLE ')

names, ranges = [], collections.defaultdict(list)
for cp in range(0x110000):
    n = unicodedata.name(chr(cp), None)
    if not n:
        continue
    p = next((a for a in ALG if n.startswith(a)), None)
    if p is None:
        names.append((cp, n))
        continue
    if p == 'HANGUL SYLLABLE ':
        continue
    assert n == p + '%04X' % cp, n
    r = ranges[p]
    if r and r[-1][1] == cp - 1:
        r[-1][1] = cp
    else:
        r.append([cp, cp])
assert all(unicodedata.lookup('HANGUL SYLLABLE ' + unicodedata.name(chr(c))[16:]) == chr(c) for c in range(0xAC00, 0xD7A4))

# word dictionary, most frequent first; variable-length codes over an alphabet without \ ` $ ~ and the 8 header chars
words_of = lambda n: n.split(' ')
cnt = collections.Counter()
for _, n in names:
    cnt.update(words_of(n))
words = [w for w, _ in cnt.most_common()]
idx = {w: i for i, w in enumerate(words)}
HEAD = '!"#%&\'()'                     # entry start: number of words shared with the previous name (0-7)
ALPHA = [chr(c) for c in range(0x21, 0x7f) if chr(c) not in '\\`$~' + HEAD]
B = len(ALPHA)
N1, N2 = B - 22, 20                    # 1-char codes, 2-char prefixes; the last 2 chars start 3-char codes
assert len(words) <= N1 + N2 * B + 2 * B * B, len(words)
def code(i):
    if i < N1:
        return ALPHA[i]
    i -= N1
    if i < N2 * B:
        return ALPHA[N1 + i // B] + ALPHA[i % B]
    i -= N2 * B
    return ALPHA[N1 + N2 + i // (B * B)] + ALPHA[(i // B) % B] + ALPHA[i % B]
out, prev, pc = [], [], -1
for cp, n in names:
    t = words_of(n)
    k = 0
    while k < len(t) - 1 and k < len(prev) and t[k] == prev[k] and k < 7:
        k += 1
    gap = cp - pc - 1
    out.append(('~' + format(gap, 'x') if gap else '') + HEAD[k] + ''.join(code(idx[w]) for w in t[k:]))
    prev, pc = t, cp
data = ''.join(out)
assert '`' not in data and '\\' not in data and '${' not in data

aliases = []
for line in open(sys.argv[1], encoding='utf-8'):
    line = line.split('#')[0].strip()
    if not line:
        continue
    cp, alias, kind = line.split(';')
    cp = int(cp, 16)
    assert unicodedata.lookup(alias) == chr(cp), alias
    aliases.append('%s:%x' % (alias, cp))

rng = {p: ','.join('%x-%x' % (a, b) for a, b in r) for p, r in ranges.items()}
js = f'''// minipy — Unicode 15.1.0 character names (CPython 3.13's unicodedata) for \\N{{...}} escapes.
// Generated by scripts/gen-minipy-unicode.py from python3.13 and NameAliases.txt; do not edit.
// WORDS: the words of the names, most frequent first. DATA: one entry per named code point in order: an optional
// '~' + hex gap (unnamed code points skipped), a header char from {HEAD!r} = number of words shared with the previous
// name, then the other words as codes over ALPHA (1 char for the first {N1} words, 2 or 3 chars for the rest).
// Algorithmic names (CJK / Tangut / Khitan / Nushu ideographs, Hangul syllables) are computed from RANGES.

const WORDS = {' '.join(words)!r};
const DATA = `{data}`;
const ALIASES = {';'.join(aliases)!r};
const RANGES = {rng!r};
const HEAD = {HEAD!r};
const ALPHA = {''.join(ALPHA)!r};
const N1 = {N1}, N2 = {N2};
''' + r'''
let table = null;
function build() {
  table = new Map();
  const words = WORDS.split(' ');
  const B = ALPHA.length;
  const val = new Int16Array(128).fill(-1);
  for (let i = 0; i < B; i++) val[ALPHA.charCodeAt(i)] = i;
  const head = new Int8Array(128).fill(-1);
  for (let i = 0; i < HEAD.length; i++) head[HEAD.charCodeAt(i)] = i;
  let cp = -1, prev = [];
  let i = 0;
  const n = DATA.length;
  while (i < n) {
    let c = DATA.charCodeAt(i);
    let gap = 0;
    if (c === 126) {   // '~'
      let j = i + 1;
      while (head[DATA.charCodeAt(j)] < 0) j++;
      gap = parseInt(DATA.slice(i + 1, j), 16);
      i = j; c = DATA.charCodeAt(i);
    }
    cp += gap + 1;
    const cur = prev.slice(0, head[c]);
    i++;
    while (i < n) {
      const d = DATA.charCodeAt(i);
      if (d === 126 || head[d] >= 0) break;
      let v = val[d];
      i++;
      if (v >= N1) {
        if (v < N1 + N2) v = N1 + (v - N1) * B + val[DATA.charCodeAt(i++)];
        else { v = N1 + N2 * B + (v - N1 - N2) * B * B + val[DATA.charCodeAt(i)] * B + val[DATA.charCodeAt(i + 1)]; i += 2; }
      }
      cur.push(words[v]);
    }
    table.set(cur.join(' '), cp);
    prev = cur;
  }
  for (const a of ALIASES.split(';')) { const k = a.lastIndexOf(':'); table.set(a.slice(0, k), parseInt(a.slice(k + 1), 16)); }
}
const JAMO_L = ['G', 'GG', 'N', 'D', 'DD', 'R', 'M', 'B', 'BB', 'S', 'SS', '', 'J', 'JJ', 'C', 'K', 'T', 'P', 'H'];
const JAMO_V = ['A', 'AE', 'YA', 'YAE', 'EO', 'E', 'YEO', 'YE', 'O', 'WA', 'WAE', 'OE', 'YO', 'U', 'WEO', 'WE', 'WI', 'YU', 'EU', 'YI', 'I'];
const JAMO_T = ['', 'G', 'GG', 'GS', 'N', 'NJ', 'NH', 'D', 'L', 'LG', 'LM', 'LB', 'LS', 'LT', 'LP', 'LH', 'M', 'B', 'BS', 'S', 'SS', 'NG', 'J', 'C', 'K', 'T', 'P', 'H'];
let hangul = null;
function inRanges(spec, cp) {
  for (const r of spec.split(',')) { const k = r.indexOf('-'); if (cp >= parseInt(r.slice(0, k), 16) && cp <= parseInt(r.slice(k + 1), 16)) return true; }
  return false;
}
/**
 * The code point named `name` in a \N{...} escape (any ASCII case, aliases included, like CPython 3.13), or -1.
 * @param {string} name
 */
export function lookupUnicodeName(name) {
  if (/[^\x20-\x7e]/.test(name)) return -1;
  const up = name.replace(/[a-z]+/g, (s) => s.toUpperCase());
  for (const p in RANGES) {
    if (!up.startsWith(p)) continue;
    const hex = up.slice(p.length);
    if (!/^[0-9A-F]{4,5}$/.test(hex)) return -1;
    const cp = parseInt(hex, 16);
    if (cp.toString(16).toUpperCase().padStart(4, '0') !== hex || !inRanges(RANGES[p], cp)) return -1;
    return cp;
  }
  if (up.startsWith('HANGUL SYLLABLE ')) {
    if (!hangul) {
      hangul = new Map();
      for (let s = 0; s < 11172; s++) hangul.set(JAMO_L[Math.floor(s / 588)] + JAMO_V[Math.floor((s % 588) / 28)] + JAMO_T[s % 28], 0xAC00 + s);
    }
    const cp = hangul.get(up.slice(16));
    return cp === undefined ? -1 : cp;
  }
  if (!table) build();
  const cp = table.get(up);
  return cp === undefined ? -1 : cp;
}
'''
open(os.path.join(os.path.dirname(__file__), '..', 'src', 'lib', 'minipy', 'uninames.js'), 'w', encoding='utf-8').write(js)
print('uninames.js:', len(names), 'names,', len(words), 'words,', len(js), 'bytes')


# ------------------------------------------------------------------------------------------------- unidata.js
B64 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'
def vlq(n):
    """unsigned: base-32 digits, most significant first; digits of a continuing number use the upper half"""
    assert n >= 0
    ds = []
    while True:
        ds.append(n & 31)
        n >>= 5
        if not n:
            break
    ds.reverse()
    return ''.join(B64[d + 32] for d in ds[:-1]) + B64[ds[-1]]
zig = lambda n: n * 2 if n >= 0 else -n * 2 - 1

def cased(ch):
    return (ch + 'a').title()[-1] == 'a'
def case_ignorable(ch):
    if cased(ch):
        return (ch + 'Σ').lower()[-1] == 'σ'
    return ('AΣ' + ch + 'B').lower()[1] == 'σ'
FLAGS = [
    ('ALPHA', str.isalpha), ('DECIMAL', str.isdecimal), ('DIGIT', str.isdigit), ('NUMERIC', str.isnumeric),
    ('PRINTABLE', str.isprintable), ('SPACE', str.isspace), ('LOWER', str.islower), ('UPPER', str.isupper),
    ('TITLE', lambda ch: unicodedata.category(ch) == 'Lt'), ('CASED', cased), ('IGNORABLE', case_ignorable),
    ('XID_START', str.isidentifier), ('XID_CONT', lambda ch: ('a' + ch).isidentifier()),
    ('ASSIGNED', lambda ch: unicodedata.category(ch) != 'Cn'),
]
masks, mask_ix, runs = [], {}, []
prev, length = None, 0
for cp in range(0x110000):
    ch = chr(cp)
    m = 0
    for i, (_, f) in enumerate(FLAGS):
        if f(ch):
            m |= 1 << i
    if m != prev:
        if prev is not None:
            runs.append((length, mask_ix[prev]))
        if m not in mask_ix:
            mask_ix[m] = len(masks)
            masks.append(m)
        prev, length = m, 0
    length += 1
runs.append((length, mask_ix[prev]))
flag_data = ''.join(vlq(n) + vlq(k) for n, k in runs)

# decimal values: Nd digits come in runs of ten starting at 0 (checked)
for cp in range(0x110000):
    ch = chr(cp)
    if ch.isdecimal():
        z = cp
        while chr(z - 1).isdecimal():
            z -= 1
        assert unicodedata.decimal(ch) == (cp - z) % 10, hex(cp)

def case_data(fn):
    ents, multi = [], []
    for cp in range(0x110000):
        ch = chr(cp)
        m = fn(ch)
        if m == ch:
            continue
        if len(m) == 1:
            ents.append((cp, ord(m) - cp))
        else:
            multi.append('%x:%s' % (cp, '.'.join('%x' % ord(x) for x in m)))
    out, i, last = [], 0, 0
    while i < len(ents):
        cp, d = ents[i]
        j, stride = i + 1, None
        while j < len(ents) and ents[j][1] == d:
            st = ents[j][0] - ents[j - 1][0]
            if stride is None and st in (1, 2):
                stride = st
            if st != stride:
                break
            j += 1
        out.append(vlq(cp - last) + vlq(j - i - 1) + vlq((stride or 1) - 1) + vlq(zig(d)))
        last = ents[j - 1][0]
        i = j
    return ''.join(out), ','.join(multi)
up_runs, up_multi = case_data(str.upper)
lo_runs, lo_multi = case_data(str.lower)
assert not lo_multi.replace('130:69.307', ''), lo_multi

flag_consts = '\n'.join('export const U_%s = %d;' % (name, 1 << i) for i, (name, _) in enumerate(FLAGS))
js = f"""// minipy — Unicode 15.1.0 character properties and case mappings, as CPython 3.13 sees them (str.isalpha(),
// isdecimal(), isdigit(), isnumeric(), isprintable(), isspace(), islower() / isupper() (derived Lowercase /
// Uppercase), category Lt, Cased, Case_Ignorable, isidentifier()'s XID_Start / XID_Continue, assigned (not Cn),
// and the full upper / lower mappings). The JS engine's own Unicode data (\\p{{...}}, toUpperCase) follows its own,
// usually newer, Unicode version, so none of it is used for non-ASCII text.
// Generated by scripts/gen-minipy-unicode.py with python3.13; do not edit.
// FLAGS: runs over all code points, each a VLQ length and a VLQ index into MASKS. UPPER / LOWER: runs of 1:1 mappings
// (VLQ gap from the previous run's last code point, count - 1, stride - 1, zigzag delta); *_MULTI: mappings to
// several characters.

{flag_consts}
const MASKS = {masks!r};
const FLAGS = '{flag_data}';
const UPPER = '{up_runs}';
const UPPER_MULTI = '{up_multi}';
const LOWER = '{lo_runs}';
const LOWER_MULTI = '{lo_multi}';
""" + r"""
const B64 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
function reader(s) {
  let i = 0;
  const val = new Int8Array(128);
  for (let k = 0; k < 64; k++) val[B64.charCodeAt(k)] = k;
  return {
    more: () => i < s.length,
    next() { let n = 0; for (;;) { const d = val[s.charCodeAt(i++)]; if (d < 32) return n * 32 + d; n = n * 32 + d - 32; } },
  };
}
let starts = null, kinds = null, ascii = null;
function buildFlags() {
  const r = reader(FLAGS);
  const st = [], kd = [];
  let cp = 0;
  while (r.more()) { const n = r.next(), k = r.next(); st.push(cp); kd.push(MASKS[k]); cp += n; }
  starts = Int32Array.from(st); kinds = Int32Array.from(kd);
  ascii = new Int32Array(128);
  for (let c = 0; c < 128; c++) ascii[c] = lookup(c);
}
function lookup(cp) {
  let lo = 0, hi = starts.length - 1;
  while (lo < hi) { const mid = (lo + hi + 1) >> 1; if (starts[mid] <= cp) lo = mid; else hi = mid - 1; }
  return kinds[lo];
}
/** the U_* flags of a code point */
export function uflags(cp) {
  if (!starts) buildFlags();
  return cp < 128 ? ascii[cp] : lookup(cp);
}
/** true when every character of s has one of the flags in `mask` (false for '') */
export function allHave(s, mask) {
  if (!s) return false;
  for (let i = 0; i < s.length; i++) {
    const c = s.codePointAt(i);
    if (c > 0xffff) i++;
    if (!(uflags(c) & mask)) return false;
  }
  return true;
}
/** Py_UNICODE_TODECIMAL: the decimal digits come in runs of ten, 0 to 9 */
export function decimalValue(cp) {
  if (cp >= 0x30 && cp <= 0x39) return cp - 0x30;
  if (!(uflags(cp) & U_DECIMAL)) return -1;
  let z = cp;
  while (uflags(z - 1) & U_DECIMAL) z--;
  return (cp - z) % 10;
}
function caseTable(runs, multi) {
  const m = new Map();
  const r = reader(runs);
  let last = 0;
  while (r.more()) {
    let cp = last + r.next();
    const count = r.next() + 1, stride = r.next() + 1, z = r.next();
    const d = z & 1 ? -(z + 1) / 2 : z / 2;
    for (let k = 0; k < count; k++, cp += stride) m.set(cp, String.fromCodePoint(cp + d));
    last = cp - stride;
  }
  if (multi) for (const e of multi.split(',')) { const [k, v] = e.split(':'); m.set(parseInt(k, 16), String.fromCodePoint(...v.split('.').map((h) => parseInt(h, 16)))); }
  return m;
}
let upperMap = null, lowerMap = null;
/** full uppercase mapping of one character (str.upper()) */
export function upperOf(ch) {
  if (!upperMap) upperMap = caseTable(UPPER, UPPER_MULTI);
  const t = upperMap.get(ch.codePointAt(0));
  return t === undefined ? ch : t;
}
/** full lowercase mapping of one character, without the final-sigma rule (str.lower()) */
export function lowerOf(ch) {
  if (!lowerMap) lowerMap = caseTable(LOWER, LOWER_MULTI);
  const t = lowerMap.get(ch.codePointAt(0));
  return t === undefined ? ch : t;
}
"""
